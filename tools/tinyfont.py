def text_bitmap(text, spacing=1):
    cols = []
    for k, ch in enumerate(text.upper()):
        g = G[ch]
        a = np.array([[c == '#' for c in row] for row in g], bool)
        if k:
            cols.append(np.zeros((5, spacing), bool))
        cols.append(a)
    return np.hstack(cols) if cols else np.zeros((5, 0), bool)


def render(text, w, h=8, fill=0xF, outline=0xE, bg=0, align='center', x_off=None, y_top=None):
    """Return h x w index image with outlined tiny text."""
    ink = text_bitmap(text)
    tw = ink.shape[1]
    out = np.full((h, w), bg, np.uint8)
    need = tw + (2 if outline is not None else 0)
    if need > w:
        raise ValueError('text %r too wide (%d > %d)' % (text, need, w))
    x0 = (w - tw) // 2 if align == 'center' else (1 if align == 'left' else w - tw - 1)
    if x_off is not None:
        x0 = x_off
    y0 = (h - 5) // 2 if y_top is None else y_top
    m = np.zeros((h, w), bool)
    m[y0:y0 + 5, x0:x0 + tw] = ink
    if outline is not None:
        o = np.zeros_like(m)
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                o |= np.roll(np.roll(m, dy, 0), dx, 1)
        out[o] = outline
    out[m] = fill
    return out


def width(text):
    return text_bitmap(text).shape[1] + 2
